    return (
        f"| {label} | {table['documents']} | {_cell(table['none']['wer_as_read'], 100, 2, ' %')} "
        f"| {_cell(default['d_wer'], 100, 2)} | {_cell(default['net_fixed_per_100_wrong'])} "
        f"| {_cell(thorough['d_wer'], 100, 2)} | {_cell(thorough['net_fixed_per_100_wrong'])} "
        f"| {_cell(paired)} |"
    )


