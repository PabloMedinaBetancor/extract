def _floor_line(language: str, data: dict) -> str:
    """The broken-share rule, `more` on T5: its d WER interval is below zero and the words it broke are at most 7.5 % of the ones it fixed
    (the 5 % of the out-of-fold rule plus 2.5 points for the shift)."""
    parts = []
    for model, name in (("default", "default model"), ("thorough", "thorough mode")):
        more = data["models"][model]["more"]
        share = more["broken"] / more["fixed"]
        meets = share <= MORE_BREAK_FLOOR and more["d_wer"]["high"] < 0
        parts.append(
            f"{name} {share * 100:.2f} % ({more['broken']} of {more['fixed']}) "
            + ("meets" if meets else "misses")
            + " it"
        )
    return (
        f"- {LANGUAGE_NAMES[language]}, floor of `more` (its WER interval below zero and the words it broke at most "
        f"{MORE_BREAK_FLOOR * 100:.1f} % of the ones it fixed), all pages: " + "; ".join(parts) + "."
    )


