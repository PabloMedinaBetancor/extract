def _ci(entry: dict, scale: float = 1.0, digits: int = 1, unit: str = "") -> str:
    """`value (low to high)` of an interval entry, scaled."""
    value, low, high = (entry[k] * scale for k in ("value", "low", "high"))
    return f"{value:.{digits}f}{unit} ({low:.{digits}f} to {high:.{digits}f})"


def _signed(entry: dict, scale: float = 1.0, digits: int = 2) -> str:
    value, low, high = (entry[k] * scale for k in ("value", "low", "high"))
    return f"{value:+.{digits}f} ({low:+.{digits}f} to {high:+.{digits}f})"


def _model_line(name: str, cell: dict) -> str:
    more = cell["more"]
    return (
        f"{name}: WER {_signed(more['d_wer'], 100)} points, fixed {more['fixed']:,}, broken {more['broken']:,}, "
        f"applied {more['applied']:,}, precision {_ci(more['precision'], 100, 1, ' %')}, "
        f"net {_ci(more['net_fixed_per_100_wrong'])} per 100 wrong words"
    )


