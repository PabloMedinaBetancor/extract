def _resolve(schema: dict, root: dict) -> dict:
    while "$ref" in schema:
        schema = root["$defs"][schema["$ref"].rsplit("/", 1)[1]]
    return schema


def _non_null(schema: dict, root: dict) -> tuple[dict, bool]:
    """The schema without the `null` alternative, and whether `null` is allowed."""
    schema = _resolve(schema, root)
    if "anyOf" in schema:
        options = [_resolve(item, root) for item in schema["anyOf"]]
        rest = [item for item in options if item != {"type": "null"}]
        return (rest[0] if len(rest) == 1 else schema), len(rest) != len(options)
    return schema, False


def _type_name(schema: dict, root: dict, path: str, objects: dict) -> tuple[str, bool]:
    """A reader's name for the type of a property, and whether `null` is a valid value."""
    if schema.get("$ref", "").endswith("/cell"):
        return "cell or `null`, see [`cell`](#cell)", False
    schema, nullable = _non_null(schema, root)
    types = schema.get("type")
    if isinstance(types, list):
        nullable = nullable or "null" in types
        types = [t for t in types if t != "null"]
        types = types[0] if len(types) == 1 else None
    if "const" in schema:
        return f"always `{json.dumps(schema['const'])}`", False
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        return "one of " + ", ".join(f"`{json.dumps(v)}`" for v in values), None in schema["enum"]
    if types == "array":
        items, _ = _non_null(schema["items"], root)
        if items.get("type") == "object" and items.get("properties"):
            objects[path + "[]"] = items
            return f"array of [`{path}[]`](#{slugify(path + '[]')})", nullable
        if "enum" in items:
            return "array of " + " or ".join(f"`{json.dumps(v)}`" for v in items["enum"]), nullable
        item_type = items["type"] if isinstance(items.get("type"), str) else _type_name(items, root, path, objects)[0]
        if "minItems" in schema and schema.get("minItems") == schema.get("maxItems"):
            return f"array of {schema['minItems']} {item_type}s", nullable
        return f"array of {item_type}s", nullable
    if types == "object":
        if schema.get("properties"):
            objects[path] = schema
            return f"object, see [`{path}`](#{slugify(path)})", nullable
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"object of {_type_name(extra, root, path, objects)[0]}s", nullable
        return "object", nullable
    text = types or "any"
    if "pattern" in schema:
        text += f" matching `{schema['pattern']}`"
    if "minimum" in schema and types == "integer":
        text += f", at least {schema['minimum']}"
    return text, nullable


def json_table(path: str, schema: dict, root: dict, objects: dict, order: list[str] | None = None) -> list[str]:
    """One row per key: its type and its meaning, which starts with "Optional." for a key a file may leave out."""
    required = set(schema.get("required", ()))
    names = order or list(schema["properties"])
    lines = ["| Key | Type | Meaning |", "|---|---|---|"]
    for name in names:
        prop = schema["properties"][name]
        full = f"{path}.{name}" if path else name
        text, nullable = _type_name(prop, root, full, objects)
        if nullable:
            text += " or `null`"
        meaning = JSON_MEANINGS.get(full)
        if meaning is None:
            raise SystemExit(f"api_docs.py: the schema key `{full}` has no entry in JSON_MEANINGS")
        meaning = meaning if name in required else "Optional. " + meaning
        lines.append(f"| `{name}` | {table_cell(text)} | {table_cell(meaning)} |")
    return lines


